export function computeProfile(answers) {
  const scores = [0, 0, 0]
  answers.forEach(answer => {
    if (answer && answer.scores) {
      answer.scores.forEach((s, i) => { scores[i] += s })
    }
  })
  const maxScore = Math.max(...scores)
  const winnerIdx = scores.indexOf(maxScore)
  return winnerIdx + 1
}
